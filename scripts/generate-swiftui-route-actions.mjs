import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const specPath = resolve(root, 'docs/spec/swiftui-route-actions.json');
const tsPath = resolve(root, 'src/app/swiftui-route-actions.generated.ts');
const swiftPath = resolve(
  root,
  'modules/hermes-ios-controls/ios/HermesSwiftUIRouteActions.generated.swift',
);
const pythonPath = resolve(
  root,
  'contracts/python/hermes_swiftui_route_actions.py',
);
const spec = JSON.parse(await readFile(specPath, 'utf8'));
if (
  spec.version !== 1
  || !Array.isArray(spec.snapshotFields)
  || !Array.isArray(spec.actionPayloadFields)
  || !spec.actions
  || typeof spec.actions !== 'object'
) {
  throw new Error('Invalid SwiftUI route action specification');
}
const snapshotFields = spec.snapshotFields;
if (
  !snapshotFields.length
  || snapshotFields[0] !== 'version'
  || new Set(snapshotFields).size !== snapshotFields.length
  || snapshotFields.some((field) => typeof field !== 'string' || !/^[a-z][A-Za-z0-9]*$/.test(field))
) {
  throw new Error('SwiftUI snapshot fields must be unique identifiers beginning with version');
}
const payloadTypes = {
  boolean: { swift: 'Bool', ts: 'boolean' },
  integer: { swift: 'Int', ts: 'number' },
  string: { swift: 'String', ts: 'string' },
  stringArray: { swift: '[String]', ts: 'readonly string[]' },
  stringMap: { swift: '[String: String]', ts: 'Readonly<Record<string, string>>' },
};
const actionPayloadFields = spec.actionPayloadFields;
if (
  !actionPayloadFields.length
  || actionPayloadFields[0]?.name !== 'route'
  || actionPayloadFields[0]?.required !== true
  || new Set(actionPayloadFields.map(({ name }) => name)).size !== actionPayloadFields.length
) {
  throw new Error('SwiftUI action payload fields must be unique and begin with required route');
}
for (const field of actionPayloadFields) {
  if (
    !field
    || typeof field.name !== 'string'
    || !/^[a-z][A-Za-z0-9]*$/.test(field.name)
    || !(field.type in payloadTypes)
    || (field.required !== undefined && typeof field.required !== 'boolean')
  ) {
    throw new Error(`Invalid SwiftUI action payload field: ${JSON.stringify(field)}`);
  }
}
const entries = Object.entries(spec.actions);
if (!entries.length || new Set(entries.map(([, value]) => value)).size !== entries.length) {
  throw new Error('SwiftUI route actions must be non-empty and unique');
}
for (const [key, value] of entries) {
  if (!/^[a-z][A-Za-z0-9]*$/.test(key) || typeof value !== 'string' || !value.includes('.')) {
    throw new Error(`Invalid SwiftUI route action: ${key}`);
  }
}

const header = '// Generated by scripts/generate-swiftui-route-actions.mjs. Do not edit.\n';
const tsPayloadProperties = actionPayloadFields
  .map(({ name, type, required = false }) => `  ${name}${required ? '' : '?'}: ${payloadTypes[type].ts};`)
  .join('\n');
const tsPayloadChecks = actionPayloadFields
  .map(({ name, type, required = false }) => {
    const accessor = `value.${name}`;
    const check = type === 'string'
      ? `typeof ${accessor} === 'string'`
      : type === 'boolean'
        ? `typeof ${accessor} === 'boolean'`
        : type === 'integer'
          ? `typeof ${accessor} === 'number' && Number.isInteger(${accessor})`
          : type === 'stringArray'
            ? `Array.isArray(${accessor}) && ${accessor}.every((entry) => typeof entry === 'string')`
            : `isGeneratedRecord(${accessor}) && Object.values(${accessor}).every((entry) => typeof entry === 'string')`;
    return `  if (${required ? `!(${check})` : `${accessor} !== undefined && !(${check})`}) return false;`;
  })
  .join('\n');
const payloadFieldNames = actionPayloadFields.map(({ name }) => `  '${name}',`).join('\n');
const ts = `${header}export const HERMES_SWIFTUI_ROUTE_SNAPSHOT_VERSION = ${spec.version} as const;\n\nexport const HERMES_SWIFTUI_ROUTE_SNAPSHOT_FIELDS = [\n${snapshotFields
  .map((field) => `  '${field}',`)
  .join('\n')}\n] as const;\n\nexport const HERMES_SWIFTUI_ROUTE_ACTION_PAYLOAD_FIELDS = [\n${payloadFieldNames}\n] as const;\n\nexport interface HermesSwiftUIRouteActionPayload {\n${tsPayloadProperties}\n}\n\nconst actionPayloadFieldNames = new Set<string>(HERMES_SWIFTUI_ROUTE_ACTION_PAYLOAD_FIELDS);\n\nexport function isHermesSwiftUIRouteActionPayload(\n  value: unknown,\n): value is HermesSwiftUIRouteActionPayload {\n  if (!isGeneratedRecord(value)) return false;\n  if (Object.keys(value).some((field) => !actionPayloadFieldNames.has(field))) return false;\n${tsPayloadChecks}\n  return true;\n}\n\nfunction isGeneratedRecord(value: unknown): value is Record<string, unknown> {\n  return typeof value === 'object' && value !== null && !Array.isArray(value);\n}\n\nexport const HERMES_SWIFTUI_ROUTE_ACTIONS = {\n${entries
  .map(([key, value]) => `  ${key}: '${value}',`)
  .join('\n')}\n} as const;\n`;
const swiftPayloadProperties = actionPayloadFields
  .map(({ name, type, required = false }) => `  let ${name}: ${payloadTypes[type].swift}${required ? '' : '?'}`)
  .join('\n');
const swiftPayloadParameters = actionPayloadFields
  .map(({ name, type, required = false }) => `    ${name}: ${payloadTypes[type].swift}${required ? '' : '? = nil'}`)
  .join(',\n');
const swiftPayloadAssignments = actionPayloadFields
  .map(({ name }) => `    self.${name} = ${name}`)
  .join('\n');
const swift = `${header}\nlet hermesRouteSnapshotVersion = ${spec.version}\n\nenum HermesRouteSnapshotField: String, CodingKey, CaseIterable {\n${snapshotFields
  .map((field) => `  case ${field}`)
  .join('\n')}\n}\n\nstruct HermesRouteActionPayload: Encodable, Equatable {\n${swiftPayloadProperties}\n\n  init(\n${swiftPayloadParameters}\n  ) {\n${swiftPayloadAssignments}\n  }\n}\n\nenum HermesRouteAction: String, CaseIterable {\n${entries
  .map(([key, value]) => `  case ${key} = "${value}"`)
  .join('\n')}\n}\n`;
const pythonHeader = '# Generated by scripts/generate-swiftui-route-actions.mjs. Do not edit.\n';
const pythonPayloadFields = actionPayloadFields
  .map(({ name, type, required = false }) => `    ${JSON.stringify(name)}: (${JSON.stringify(type)}, ${required ? 'True' : 'False'}),`)
  .join('\n');
const python = `${pythonHeader}from __future__ import annotations\n\nfrom typing import Final, TypeGuard\n\nSCHEMA_VERSION: Final = ${spec.version}\nSNAPSHOT_FIELDS: Final = (\n${snapshotFields
  .map((field) => `    ${JSON.stringify(field)},`)
  .join('\n')}\n)\nACTION_PAYLOAD_FIELDS: Final = {\n${pythonPayloadFields}\n}\nACTIONS: Final = {\n${entries
  .map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join('\n')}\n}\n\ndef is_route_action_payload(value: object) -> TypeGuard[dict[str, object]]:\n    if not isinstance(value, dict) or not set(value).issubset(ACTION_PAYLOAD_FIELDS):\n        return False\n    for name, (kind, required) in ACTION_PAYLOAD_FIELDS.items():\n        if required and name not in value:\n            return False\n        if name in value and not _matches_payload_type(value[name], kind):\n            return False\n    return True\n\ndef _matches_payload_type(value: object, kind: str) -> bool:\n    if kind == "string":\n        return isinstance(value, str)\n    if kind == "boolean":\n        return isinstance(value, bool)\n    if kind == "integer":\n        return isinstance(value, int) and not isinstance(value, bool)\n    if kind == "stringArray":\n        return isinstance(value, list) and all(isinstance(item, str) for item in value)\n    if kind == "stringMap":\n        return isinstance(value, dict) and all(\n            isinstance(key, str) and isinstance(item, str)\n            for key, item in value.items()\n        )\n    return False\n`;

if (process.argv.includes('--check')) {
  const [currentTs, currentSwift, currentPython] = await Promise.all([
    readFile(tsPath, 'utf8'),
    readFile(swiftPath, 'utf8'),
    readFile(pythonPath, 'utf8'),
  ]);
  if (currentTs !== ts || currentSwift !== swift || currentPython !== python) {
    throw new Error('Generated SwiftUI route actions are stale');
  }
} else {
  await Promise.all([
    writeFile(tsPath, ts, 'utf8'),
    writeFile(swiftPath, swift, 'utf8'),
    writeFile(pythonPath, python, 'utf8'),
  ]);
}
